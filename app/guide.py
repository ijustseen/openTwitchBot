from __future__ import annotations

import webbrowser

from app.store import resource_root

PROMPT = """Ты пишешь команду для локального Twitch-бота OpenBot.
Команда — это один файл Python с функцией run(ctx). Функция обычная, не async.

Что приходит в ctx, когда зритель пишет в чат, например, «!hello мир всем» на канале mychannel:
- ctx.user — отображаемое имя автора, с тем регистром, как в чате.
- ctx.user_id — числовой id Twitch. Ник можно сменить, id нет.
- ctx.args — список слов после команды. Для примера выше это ["мир", "всем"]. Самой команды в списке нет. Если слов нет, список пустой.
- ctx.message — вся строка целиком, вместе с командой: "!hello мир всем".
- ctx.channel — имя канала из настроек бота, строчными буквами и без решётки: "mychannel".
- ctx.is_mod — True у модератора и у владельца канала. У обычного зрителя False.
- ctx.is_broadcaster — True только у владельца канала.

Как отвечать:
- ctx.reply("текст") отправляет строку в чат. Вызов можно повторить: в чат уйдут первые 5 непустых ответов.
- Каждый ответ схлопывается в одну строку и обрезается до 500 символов.
- print(...) в чат не попадает. Это строка в лог окна OpenBot.

Правила кода:
- Обязательна функция run(ctx). Другие функции рядом можно.
- Не используй async и await.
- Не импортируй twitchio и не трогай окно программы. Доступны обычные модули Python.
- Скрипт обрывается примерно через 10 секунд.
- Песочницы нет: скрипт может читать файлы и ходить в сеть от имени пользователя. Не проси вставлять в команду токен Twitch и пароли.
- Если команда в окне стоит в режиме «Модераторы и стример», обычный зритель до run(ctx) не доходит. ctx.is_mod внутри скрипта нужен, когда команда доступна всем, а ответ модератору другой.

Пример:

def run(ctx):
    if not ctx.args:
        ctx.reply(f"@{ctx.user}, напишите имя после команды")
        return
    ctx.reply(f"{ctx.user}: {' '.join(ctx.args)}")

Когда пользователь просит команду, верни полный файл, который можно сохранить как есть.
"""


def wiki_path():
    return resource_root() / "docs" / "index.html"


def open_wiki() -> None:
    path = wiki_path()
    if not path.is_file():
        raise FileNotFoundError(path)
    webbrowser.open(path.resolve().as_uri())
